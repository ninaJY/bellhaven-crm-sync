"""Bellhaven CRM Sync — local Streamlit approval dashboard.

Project layout:
    bellhaven-crm-sync/
      match.py
      app.py
      data/crm_snapshot.json
      data/scraped_locations.json
      reconcile_output/review_proposals.json  # generated by match.py

Run:
    python match.py
    python -m streamlit run app.py

This app stores decisions locally only. It never calls the CRM API.
"""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
PROPOSALS_FILE = BASE_DIR / "reconcile_output" / "review_proposals.json"
STATE_FILE = BASE_DIR / "reconcile_output" / "review_states.json"

st.set_page_config(page_title="Bellhaven CRM Sync Review", page_icon="🏥", layout="wide")

# Buttons have permanently distinct colors, regardless of selection state.
st.markdown("""
<style>
/* Streamlit wraps keyed widgets in st-key-* containers. */
[class*="st-key-approve_"] button[kind],
[class*="st-key-approve_"] button {
    background-color: #16803c !important;
    border: 1px solid #16803c !important;
    color: white !important;
}
[class*="st-key-approve_"] button:hover {background-color:#126530 !important; color:white !important;}
[class*="st-key-reject_"] button[kind],
[class*="st-key-reject_"] button {
    background-color: #cf3030 !important;
    border: 1px solid #cf3030 !important;
    color: white !important;
}
[class*="st-key-reject_"] button:hover {background-color:#a82525 !important; color:white !important;}
</style>
""", unsafe_allow_html=True)


def load_json(path: Path, default):
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        st.error(f"Could not read {path}: {exc}")
        st.stop()


def save_json_atomic(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = path.with_suffix(path.suffix + ".tmp")
    temp_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    temp_path.replace(path)


def signature(proposal: dict) -> str:
    """Invalidate old approval if any executable modification changes."""
    significant = {key: proposal.get(key) for key in
                   ("account_id", "operation", "changes", "create_payload", "candidate_ids", "review_flags")}
    encoded = json.dumps(significant, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def get_status(states: dict, proposal: dict) -> str:
    record = states.get(proposal["proposal_key"])
    if isinstance(record, dict):
        if record.get("signature") != signature(proposal):
            return "pending"  # proposal changed: old approval must not be reused
        value = record.get("decision", "pending")
        return value if value in ("approved", "rejected") else "pending"
    # Older state files may have stored only strings. Cannot safely verify them.
    return "pending"


def decide(states: dict, proposal: dict, decision: str) -> None:
    states[proposal["proposal_key"]] = {
        "decision": decision,
        "signature": signature(proposal),
        "decided_at": datetime.now(timezone.utc).isoformat(),
        "facility": proposal.get("facility", ""),
        "account_id": proposal.get("account_id"),
    }
    save_json_atomic(STATE_FILE, states)


def show_value(value):
    if value is None or value == "":
        return "(empty)"
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


proposals = load_json(PROPOSALS_FILE, [])
states = load_json(STATE_FILE, {})
if not isinstance(proposals, list) or not isinstance(states, dict):
    st.error("Expected proposals to be a JSON list and review states to be a JSON object.")
    st.stop()
if not proposals:
    st.error("No proposals found. Run `python match.py` first.")
    st.caption(f"Expected file: {PROPOSALS_FILE}")
    st.stop()
keys = [p.get("proposal_key") for p in proposals if isinstance(p, dict)]
if len(keys) != len(proposals) or any(not key for key in keys) or len(set(keys)) != len(keys):
    st.error("Invalid proposals: every proposal must have a unique proposal_key.")
    st.stop()

st.title("🏥 Bellhaven CRM Sync — Review Dashboard")
st.info("**Approve / Reject only saves your local review decision.** No changes are sent to CRM from this page.")

statuses = [get_status(states, p) for p in proposals]
counts = {name: statuses.count(name) for name in ("approved", "rejected", "pending")}

with st.sidebar:
    st.header("Review progress")
    st.metric("Total proposals", len(proposals))
    st.metric("Approved", counts["approved"])
    st.metric("Rejected", counts["rejected"])
    st.metric("Pending", counts["pending"])
    st.progress((counts["approved"] + counts["rejected"]) / len(proposals))
    status_filter = st.selectbox("Status", ["All", "Pending", "Approved", "Rejected"])
    category_filter = st.selectbox("Category", ["All"] + sorted({p.get("category", "Unknown") for p in proposals}))
    source_filter = st.selectbox("Source", ["All", "website", "crm_cleanup"])
    keyword = st.text_input("Search facility or Account ID", "")
    st.divider()
    st.caption("Decisions are saved to reconcile_output/review_states.json. Re-running match.py does not erase them.")

m1, m2, m3, m4 = st.columns(4)
m1.metric("Proposals", len(proposals))
m2.metric("Approved", counts["approved"])
m3.metric("Rejected", counts["rejected"])
m4.metric("Pending", counts["pending"])

category_names = {
    "B_MINOR_FIELD_UPDATE": "B · Minor field update",
    "C_REPARENT_EXISTING": "C · Direct re-parent",
    "D_CHOW_CREATE_AND_LINK": "D · CHOW: create & link",
    "E_RENAME_OR_REPARENT": "E · Rename / re-parent",
    "F_CREATE_NEW": "F · Create account",
    "DUPLICATE_CONFIDENT": "CRM · Duplicate",
    "NOT_ON_CURRENT_WEBSITE": "CRM · Missing from website",
}

visible = 0
for index, proposal in enumerate(proposals, start=1):
    status = get_status(states, proposal)
    category = proposal.get("category", "Unknown")
    source = proposal.get("source", "")
    facility = proposal.get("facility", "Unnamed")
    account_id = proposal.get("account_id")
    if status_filter != "All" and status != status_filter.lower():
        continue
    if category_filter != "All" and category != category_filter:
        continue
    if source_filter != "All" and source != source_filter:
        continue
    if keyword and keyword.lower() not in f"{facility} {account_id or ''}".lower():
        continue
    visible += 1
    pid = proposal["proposal_key"]
    # Safe & stable UI widget key even if proposal key includes punctuation.
    widget_id = hashlib.sha256(pid.encode("utf-8")).hexdigest()[:16]
    with st.container(border=True):
        content, controls = st.columns([4, 1], gap="large")
        with content:
            st.subheader(f"#{index} · {facility}")
            st.caption(f"{category_names.get(category, category)}  |  Operation: {proposal.get('operation', '')}  |  Source: {source}")
            st.write(f"**CRM Account ID:** `{account_id}`" if account_id else "**CRM Account:** New account")
            changes = proposal.get("changes") or []
            if changes:
                st.markdown("**Proposed changes — current → new:**")
                st.table([{
                    "Field": ch.get("field", ""),
                    "Current value": show_value(ch.get("from")),
                    "Proposed value": show_value(ch.get("to")),
                } for ch in changes])
            if proposal.get("create_payload"):
                st.markdown("**New account data:**")
                st.json(proposal["create_payload"], expanded=False)
            if proposal.get("operation") == "CHOW":
                st.warning("CHOW rule: preserve the old account/parent and billing history. Create a new Bellhaven account first, then link the OLD account's chow_current_account to the NEW ID.")
            candidates = proposal.get("candidate_ids") or []
            if len(candidates) > 1:
                st.warning("Multiple account candidates — verify before approval: " + ", ".join(candidates))
            for flag in proposal.get("review_flags") or []:
                st.warning(flag)
            with st.expander("Evidence / supporting details", expanded=False):
                evidence = proposal.get("evidence") or {}
                if evidence.get("source_url"):
                    st.markdown(f"[Open official facility page]({evidence['source_url']})")
                st.json(evidence, expanded=True)
        with controls:
            st.markdown(f"**Status:** `{status.upper()}`")
            if st.button("✅ Approve", key=f"approve_{widget_id}", use_container_width=True):
                decide(states, proposal, "approved")
                st.rerun()
            if st.button("❌ Reject", key=f"reject_{widget_id}", use_container_width=True):
                decide(states, proposal, "rejected")
                st.rerun()
            if status != "pending" and st.button("Reset", key=f"reset_{widget_id}", use_container_width=True):
                states.pop(pid, None)
                save_json_atomic(STATE_FILE, states)
                st.rerun()

if visible == 0:
    st.warning("No proposals match these filters.")

st.divider()
st.caption("A / MATCH_NO_CHANGE facilities are intentionally absent from the approval queue. This app does not apply approved changes; an API apply step is still required for the assessment.")
